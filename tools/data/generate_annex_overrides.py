"""Generates building compositions from annexes.dat.json by three rules.

Reads assets/extracted_data/annexes.dat.json, units.json, graphics.json and
shadows.json, and assets/original/Data/graphics.drs. Prints how each building
compares with the current annexes.overrides.json; with --write, writes
assets/extracted_data/annexes.overrides.json.

The rules, applied to every building alike:

1. Offset: a piece the dat's Misplacement puts at (dx, dy) sits at (dy, -dx):
   the dat's axes turned a quarter onto the engine's.

2. Origin: the building's own piece -- the main unit's graphic -- sits on the
   building's position, and each annex at its Misplacement from there. The
   engine draws the whole about the footprint's middle (which an even
   footprint puts half a tile off the origin tile).

3. Right-hand pieces: the graphic slots are N2=left wing, N3=front left
   pillars, N4=far left pillar and N5/N6/N7 their right-hand counterparts,
   reached through graphic deltas. No unit owns them, so where a piece's
   graphic is named <base>N<k><civ> with k in 2..4, its counterpart
   <base>N<k+3><civ> is added at the same offset. These are separate graphics,
   not mirrors: flipping an isometric roof turns it perpendicular rather than
   parallel.

The shadow graphic covers the whole footprint and is placed at the main unit's
piece.

Usage:
    python3 tools/data/generate_annex_overrides.py [--write]
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata  # noqa: E402
import slp  # noqa: E402

ROOT = gamedata.ROOT
DRS = os.path.join(ROOT, 'assets', 'original', 'Data', 'graphics.drs')
OUT = os.path.join(ROOT, 'assets', 'extracted_data', 'annexes.overrides.json')

COMMENT = [
    "Generated by tools/data/generate_annex_overrides.py -- do not hand-edit;",
    "change the rules in the generator and re-run it.",
    "Offsets are the dat's Misplacement (dx, dy) turned to (dy, -dx), from the",
    "building's own piece at 0,0 (the engine draws it at the footprint's middle).",
    "Pieces named by 'slp' are the right-hand graphics (N5/N6/N7) that the original",
    "reaches through graphic deltas: no unit owns them. They are not mirrors --",
    "flipping an isometric roof turns it perpendicular instead of parallel.",
    "'counterpart' names the unit whose graphic a right-hand piece belongs to, so",
    "the engine can follow it when an age upgrades that unit; 'slp' is the fallback.",
    "'shadow' pieces carry the whole footprint's shadow; optional 'src' crops a",
    "graphic that packs several regions into one image.",
]


def counterpart_name(name):
    """<base>N<k><civ> -> <base>N<k+3><civ> for k in 2..4, else None."""
    for pos in (1, 2):
        if len(name) <= pos:
            continue
        i = len(name) - pos
        if name[i] in '234' and i >= 1 and name[i - 1] == 'N':
            return name[:i] + str(int(name[i]) + 3) + name[i + 1:]
    return None


def main():
    write = '--write' in sys.argv

    blob, entries = slp.read_drs(DRS)
    units = gamedata.load('units.json')
    graphics = gamedata.load('graphics.json')
    shadow_map = gamedata.load('shadows.json')
    dat = gamedata.load('annexes.dat.json')

    by_name = {g['name']: g for g in graphics.values() if g.get('name')}
    name_by_slp = {}
    for g in graphics.values():
        s = g.get('slp_id', -1)
        if s >= 0:
            name_by_slp.setdefault(s, g.get('name', '?'))

    def slp_of_unit(uid):
        u = units.get(str(uid))
        if not u:
            return None
        g = graphics.get(str(u.get('idle_graphic0', -1)))
        return g.get('slp_id', -1) if g else None

    def area(slp_id):
        if slp_id is None or slp_id not in entries:
            return 0
        off, _ = entries[slp_id]
        hdrs = slp.slp_frame_headers(blob, off)[2]
        return hdrs[0]['width'] * hdrs[0]['height'] if hdrs else 0

    out = {'_comment': COMMENT}
    for uid in sorted(dat, key=lambda k: int(k)):
        main_slp = slp_of_unit(uid)
        pieces = []
        if main_slp is not None and main_slp >= 0:
            pieces.append({'unit': int(uid), 'slp': main_slp, 'dx': 0.0, 'dy': 0.0})
        for a in dat[uid]:
            s = slp_of_unit(a['unit'])
            if s is None or s < 0:
                continue
            # Rule 1: the dat's axes turned a quarter.
            pieces.append({'unit': a['unit'], 'slp': s, 'dx': a['dy'], 'dy': -a['dx']})
        if not pieces:
            continue

        # Rule 2: the main unit's piece is the building's position (0, 0);
        # the annexes stand at their offsets from it.
        for p in pieces:
            p['dx'] = round(p['dx'], 3)
            p['dy'] = round(p['dy'], 3)

        # Rule 3: add the right-hand counterpart graphics.
        #
        # Each is recorded as the counterpart *of its unit*, not only as a
        # graphic: an age upgrades the unit (RTWC1B becomes RTWC2B in the
        # Feudal Age), and the engine resolves the counterpart from whatever
        # the unit has become. The graphic found here is the fallback.
        extra = []
        for p in pieces:
            other = counterpart_name(name_by_slp.get(p['slp'], ''))
            if not other:
                continue
            g = by_name.get(other)
            if not g or g.get('slp_id', -1) not in entries:
                continue
            extra.append({'slp': g['slp_id'], 'counterpart': p.get('unit', -1),
                          'dx': p['dx'], 'dy': p['dy']})
        pieces += extra

        # The shadow covers the footprint; place it on the main unit's piece.
        main_piece = next((p for p in pieces if p.get('unit') == int(uid)), pieces[0])
        shadow_slp = None
        for p in pieces:
            sid = shadow_map.get(str(p['slp']))
            if sid:
                shadow_slp = sid
                break
        # Order by depth (dx + dy), each right-hand counterpart straight after
        # its left partner. Pieces sharing a tile share a depth, so this list
        # order is what breaks the tie when they are drawn.
        pieces.sort(key=lambda p: (p['dx'] + p['dy'], 'unit' not in p))

        entry = []
        for p in pieces:
            rec = {'unit': p['unit']} if 'unit' in p else {'slp': p['slp']}
            if p.get('counterpart', -1) >= 0:
                rec['counterpart'] = p['counterpart']
            rec['dx'] = p['dx']
            rec['dy'] = p['dy']
            entry.append(rec)
        if shadow_slp:
            entry.append({'slp': shadow_slp, 'shadow': True,
                          'dx': main_piece['dx'], 'dy': main_piece['dy']})
        out[uid] = entry

    # Compare against what is already in place before overwriting anything.
    try:
        existing = gamedata.load('annexes.overrides.json')
    except FileNotFoundError:
        existing = {}

    for uid in sorted(out, key=lambda k: (k.startswith('_'), k)):
        if uid.startswith('_'):
            continue
        name = units.get(uid, {}).get('name', uid)
        old = existing.get(uid)
        if old is None:
            print('  %-6s %-9s new (%d pieces)' % (uid, name, len(out[uid])))
            continue
        same = json.dumps(old, sort_keys=True) == json.dumps(out[uid], sort_keys=True)
        print('  %-6s %-9s %s' % (uid, name, 'MATCHES tuned' if same else 'differs from tuned'))
        if not same:
            print('        tuned:     %s' % json.dumps(old))
            print('        generated: %s' % json.dumps(out[uid]))

    if write:
        with open(OUT, 'w') as fh:
            json.dump(out, fh, indent=1)
        print('\nwrote %s (%d buildings)' % (OUT, len(out) - 1))
    else:
        print('\ndry run; pass --write to save')


if __name__ == '__main__':
    main()
